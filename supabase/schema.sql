-- Sabor Brasas: esquema inicial para Supabase PostgreSQL.
-- Ejecuta en Supabase > SQL Editor. Revisa las políticas antes de producción.
create extension if not exists pgcrypto;

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  description text not null default '',
  price numeric(10,2) not null check (price >= 0),
  category text not null default 'General',
  image_url text not null default '',
  available boolean not null default true,
  featured boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_name text not null,
  customer_phone text not null,
  delivery_address text,
  fulfillment_type text not null check (fulfillment_type in ('delivery','pickup','dine_in')),
  payment_method text not null check (payment_method in ('pix','card','cash','in_person')),
  payment_status text not null default 'pending' check (payment_status in ('pending','processing','paid','failed','refunded','partially_refunded')),
  status text not null default 'new' check (status in ('new','accepted','preparing','ready','on_the_way','delivered','cancelled')),
  subtotal numeric(10,2) not null check (subtotal >= 0),
  total numeric(10,2) not null check (total >= 0),
  notes text,
  items jsonb not null default '[]'::jsonb,
  table_id uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.restaurant_tables (
  id uuid primary key default gen_random_uuid(),
  label text not null unique,
  qr_token uuid not null default gen_random_uuid() unique,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  role text not null default 'staff' check (role in ('owner','manager','cashier','waiter','kitchen')),
  created_at timestamptz not null default now()
);

create table if not exists public.expenses (
  id uuid primary key default gen_random_uuid(),
  description text not null,
  amount numeric(10,2) not null check (amount >= 0),
  category text not null default 'General',
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.payment_events (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  provider text not null,
  provider_reference text,
  event_type text not null,
  amount numeric(10,2),
  raw_event jsonb,
  created_at timestamptz not null default now()
);

create index if not exists orders_created_at_idx on public.orders(created_at desc);
create index if not exists orders_status_idx on public.orders(status);
create index if not exists products_category_idx on public.products(category);

-- updated_at
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end; $$;
drop trigger if exists orders_updated_at on public.orders;
create trigger orders_updated_at before update on public.orders
for each row execute function public.set_updated_at();

alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.restaurant_tables enable row level security;
alter table public.profiles enable row level security;
alter table public.expenses enable row level security;
alter table public.payment_events enable row level security;

-- Catálogo público: los visitantes pueden leer productos disponibles.
drop policy if exists "Public can read available products" on public.products;
create policy "Public can read available products" on public.products
for select to anon, authenticated using (available = true);

-- El personal autenticado puede leer catálogo completo.
drop policy if exists "Authenticated staff can read products" on public.products;
create policy "Authenticated staff can read products" on public.products
for select to authenticated using (true);
drop policy if exists "Authenticated staff can manage products" on public.products;
create policy "Authenticated staff can manage products" on public.products
for all to authenticated using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('owner','manager'))) with check (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('owner','manager')));

-- Nota de seguridad: NO se habilita creación pública de pedidos en estas políticas.
-- Para producción, crear una función RPC o API server-side que valide productos,
-- precios, disponibilidad, límite de pedidos y token de mesa antes de insertar.
-- No uses una policy abierta para INSERT en orders con datos enviados por el navegador.
drop policy if exists "Staff can read orders" on public.orders;
create policy "Staff can read orders" on public.orders
for select to authenticated using (exists(select 1 from public.profiles p where p.id=auth.uid()));
drop policy if exists "Staff can update orders" on public.orders;
create policy "Staff can update orders" on public.orders
for update to authenticated using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('owner','manager','cashier','waiter','kitchen'))) with check (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('owner','manager','cashier','waiter','kitchen')));

drop policy if exists "Staff can read tables" on public.restaurant_tables;
create policy "Staff can read tables" on public.restaurant_tables
for select to authenticated using (exists(select 1 from public.profiles p where p.id=auth.uid()));
drop policy if exists "Managers can manage tables" on public.restaurant_tables;
create policy "Managers can manage tables" on public.restaurant_tables
for all to authenticated using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('owner','manager'))) with check (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('owner','manager')));

drop policy if exists "Staff can read own profile" on public.profiles;
create policy "Staff can read own profile" on public.profiles
for select to authenticated using (id=auth.uid());
drop policy if exists "Owners can manage profiles" on public.profiles;
create policy "Owners can manage profiles" on public.profiles
for all to authenticated using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='owner')) with check (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='owner'));

drop policy if exists "Managers can read expenses" on public.expenses;
create policy "Managers can read expenses" on public.expenses
for select to authenticated using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('owner','manager','cashier')));
drop policy if exists "Managers can manage expenses" on public.expenses;
create policy "Managers can manage expenses" on public.expenses
for all to authenticated using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('owner','manager'))) with check (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('owner','manager')));

drop policy if exists "Managers can read payment events" on public.payment_events;
create policy "Managers can read payment events" on public.payment_events
for select to authenticated using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('owner','manager','cashier')));

